function [duty, veff_low, diag_cmd, light_state, fmh_active, ahb_state, hazard_active, ess_active, lux_filt] = LSC_cmd( ...
    ignition, sw_raw, flash_raw, hb_toggle, fog_sw, ahb_switch, turn_left, turn_right, hazard_sw, brake_pedal, ...
    lux_raw, msg_ok, speed, decel, vehicle_detected, cam_ok, door_closed, vbat, fault_prev, degraded_prev)
%#codegen
% RUNNABLE 1 (10 ms) du calculateur d'eclairage : B1 -> B2 -> B3 -> B4/B8 -> B5 -> B7
% fault_prev et degraded_prev : sorties de LSC_diag au pas precedent (donnees echangees via le RTE)
P = LSC_params_const();
persistent low_prev                      % retard d'un pas (Z_low du modele Simulink)
if isempty(low_prev), low_prev = false; end
[lux_filt, lux_valid, sw_pos, flash_req] = B1_Acquisition(lux_raw, msg_ok, sw_raw, flash_raw, ...
    P.Ts, P.TAU_LUX, P.LUX_MAX, P.T_ABSENT, P.T_RECOVER, P.T_DEB);
is_auto = (sw_pos == 1);
low_beam = AutoHeadlampLogic(lux_filt, is_auto, lux_valid, P.Ts, P.LUX_ON, P.LUX_OFF, P.T_ON, P.T_OFF, P.T_TUNNEL);
[high_beam, ahb_state] = AHB_Logic(is_auto, ahb_switch, low_prev, speed, lux_filt, vehicle_detected, cam_ok, flash_req, ...
    P.Ts, P.V_AHB_ON, P.V_AHB_OFF, P.LUX_AHB, P.T_REARM);
[low_L, low_R, high, position, drl, fog, fmh_active, light_state] = B4_Manager(ignition, sw_pos, flash_req, hb_toggle, fog_sw, ...
    low_beam, high_beam, lux_filt, vbat, door_closed, degraded_prev, P.Ts, P.LUX_ON, P.T_FMH, P.T_ARM, P.T_FMH_STEP, P.T_FMH_MAX, P.U_BAT_MIN);
low_prev = low_L || low_R;
[blink_L, blink_R, brake_light, hazard_active, ess_active] = B5_Signal(ignition, turn_left, turn_right, hazard_sw, brake_pedal, ...
    speed, decel, fault_prev(3), fault_prev(4), P.Ts, P.F_BLINK, P.F_HYPER, P.T_SHORT, P.N_COMFORT, P.A_ESS_ON, P.A_ESS_OFF, ...
    P.V_ESS, P.F_ESS, P.V_RESUME);
[duty, veff_low, diag_cmd] = B7_Driver(low_L, low_R, high, position, drl, fog, blink_L, blink_R, brake_light, vbat, ...
    P.Ts, P.V_EFF, P.T_SOFT, P.POS_DIM, P.TAIL_DIM);
